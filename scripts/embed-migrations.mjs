// Embeds drizzle/*.sql into src/server/db/migrations.ts so serverless deploys can self-migrate.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const files = readdirSync("drizzle").filter((f) => f.endsWith(".sql")).sort();
const list = files.map((f) => ({
  name: f.replace(/\.sql$/, ""),
  statements: readFileSync(`drizzle/${f}`, "utf8").split("--> statement-breakpoint").map((s) => s.trim()).filter(Boolean),
}));
writeFileSync(
  "src/server/db/migrations.ts",
  `// AUTO-GENERATED by scripts/embed-migrations.mjs — do not edit.\nexport const MIGRATIONS: { name: string; statements: string[] }[] = ${JSON.stringify(list, null, 2)};\n`,
);
console.log(`embedded ${files.length} migration(s)`);
